'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const cfg=JSON.parse(read('app.json')).expo;
const native=read('index.js'),startup=read('web/device-name-runtime.js');
assert.equal(process.env.ABU_BASSAM_DIAGNOSTIC_BUILD,'1','Sandbox requires explicit build opt-in');
assert.equal(cfg.android.package,'com.abubassam.librarycamera3.diagnostic','Sandbox must not replace production package');
assert.equal(cfg.scheme,'abu-bassam-library-diagnostic','Sandbox must never intercept production recovery URLs');
assert.ok(cfg.name.includes('فحص'),'Diagnostic app must be visibly distinct');
assert.ok(cfg.android.blockedPermissions.includes('android.permission.INTERNET'),'Sandbox must disallow network permission');
assert.ok(!cfg.android.permissions.includes('INTERNET'),'Sandbox must not request network permission');
assert.ok(native.includes('const IS_OFFLINE_DIAGNOSTIC = true;'));
assert.ok(native.includes('window.__ABU_BASSAM_DIAGNOSTIC_BUILD__ = true;'));
assert.ok(native.includes('window.__ABU_BASSAM_NATIVE_SECURITY__ = false;'));
assert.ok(native.includes("IS_OFFLINE_DIAGNOSTIC && message.type === 'security'"),'Native privileged bridge must fail closed');
assert.ok(native.includes('allowUniversalAccessFromFileURLs={false}'),'File origin must not bypass network isolation');
assert.ok(startup.includes('const OFFLINE_DIAGNOSTIC_ONLY = true;'));
const start=startup.indexOf('if(OFFLINE_DIAGNOSTIC_ONLY){');
const end=startup.indexOf('mountOfflineDiagnostic();',start);
const guard=startup.slice(start,end);
assert.ok(start>=0&&end>start,'Must have diagnostic early-return branch');
for(const forbidden of ['loadSecurity()', 'loadAccountCenter()', 'loadAccountRecoveryHardening()', 'loadBackupCenter()', 'loadAppUpdate()', 'loadAdminPermissions()', 'loadPermissionSectionGuards()'])assert.ok(!guard.includes(forbidden),'Diagnostic must not load security/account module '+forbidden);
assert.ok(startup.includes('mountOfflineDiagnostic();'),'Touch test controls must be installed without account gate');
assert.ok(startup.includes("id='abuDiagnosticBanner'")||startup.includes("banner.id='abuDiagnosticBanner'"));
assert.ok(startup.includes('abuDiagnosticTouchInput'));
assert.ok(startup.includes('abuDiagnosticTapButton'));
assert.ok(startup.includes("component:'diagnostic-shell'"),'Scoped local readiness handshake required');
assert.ok(native.includes("message.component === 'diagnostic-shell'"));
assert.ok(native.includes('pointerEvents="box-none"'),'Native probe must pass outside touches to WebView');
require('@babel/parser').parse(native,{sourceType:'module',plugins:['jsx']});
require('@babel/parser').parse(startup,{sourceType:'script'});
console.log('Sandbox guard: account gate is not loaded; isolated package, no INTERNET, secure bridge denied, touch controls, JSX and JS syntax verified.');
